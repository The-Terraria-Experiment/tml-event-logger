using System.Collections.Generic;
using Terraria.ModLoader;

namespace TteEventLogger;

/// <summary>
/// <c>eventlogger &lt;status|test|showconfig&gt;</c>, mirroring the TShock plugin's <c>/eventnotifier</c>.
/// </summary>
/// <remarks>
/// Console only. tModLoader has no permission system, so a chat command would be open to every
/// player. There is no <c>reload</c>: config changes made through tModLoader apply immediately, and
/// hand edits to the JSON need a restart.
/// </remarks>
public sealed class EventLoggerCommand : ModCommand
{
	public override string Command => "eventlogger";

	public override CommandType Type => CommandType.Console;

	public override string Usage => "eventlogger <status|test|showconfig>";

	public override string Description => "TTE event feed: dispatch stats, a test event, or the (redacted) config.";

	public override void Action(CommandCaller caller, string input, string[] args)
	{
		var publisher = EventLoggerSystem.Publisher;
		if (publisher is null)
		{
			caller.Reply("Event publisher is not running (it only runs on a dedicated server).");
			return;
		}

		switch (args.Length == 0 ? "" : args[0].ToLowerInvariant())
		{
			case "status":
				caller.Reply(publisher.BuildStatusMessage());
				break;
			case "test":
				publisher.PublishServerEvent("test.manual", new Dictionary<string, object?>
				{
					["note"] = "Manual test event generated by command.",
					["commandSource"] = "console"
				});
				caller.Reply("Test event queued.");
				break;
			case "showconfig":
				ShowConfig(caller, publisher);
				break;
			default:
				caller.Reply("Usage: " + Usage);
				break;
		}
	}

	private static void ShowConfig(CommandCaller caller, EventPublisher publisher)
	{
		var settings = publisher.Settings;
		var events = settings.Events;

		// Never print the API key itself.
		caller.Reply($"Endpoint: {(string.IsNullOrWhiteSpace(settings.EndpointUrl) ? "(not set)" : settings.EndpointUrl)}");
		caller.Reply($"API key: {(string.IsNullOrWhiteSpace(settings.ApiKey) ? "(not set)" : "(set)")}, header: {settings.ApiKeyHeaderName}");
		caller.Reply($"SchemaVersion: {settings.SchemaVersion}, timeout: {settings.RequestTimeoutMs}ms, retries: {settings.RetryCount} x {settings.RetryDelayMs}ms, queue: {settings.QueueCapacity}");
		caller.Reply($"Enabled hooks: join={events.Join}, leave={events.Leave}, chat={events.Chat}, death={events.Death}, spawn={events.Spawn}, worldsave={events.WorldSave}");
	}
}
